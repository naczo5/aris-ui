#!/usr/bin/env python3
"""Regenerate src/renderer/vk_spv.inc from the Vulkan GLSL sources.

The Vulkan backend links against checked-in SPIR-V, so this script is the link
between src/renderer/shaders/{ui.vert,ui.frag} and the arrays the renderer
consumes. Run it after editing those shaders (or the GLSL inside
src/renderer/batcher.cpp, which is the OpenGL copy of the same shader):

    make spv                 # regenerate in place
    make spv CHECK=1         # fail (non-zero) if vk_spv.inc is stale

glslang is expected at tools/glslang/bin/glslang[.exe] (git-ignored); override
with --glslang PATH or the GLSLANG environment variable.
"""
import argparse
import os
import shutil
import struct
import subprocess
import sys
import tempfile

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SHADERS = os.path.join(REPO, "src", "renderer", "shaders")
OUT = os.path.join(REPO, "src", "renderer", "vk_spv.inc")

# (glsl source, array name) — keep in sync with the include in vulkan_renderer.cpp
TARGETS = [
    ("ui.vert", "kUiVertSpv"),
    ("ui.frag", "kUiFragSpv"),
]

HEADER = ("// Generated by tools/gen_spv.py from src/renderer/shaders/* "
          "- do not edit.\n")


def default_glslang():
    env = os.environ.get("GLSLANG")
    if env:
        return env
    exe = os.path.join(REPO, "tools", "glslang", "bin", "glslang")
    if os.name == "nt":
        exe += ".exe"
    return exe


def compile_shader(glslang, source_path, spv_path):
    cmd = [glslang, "-V", "--target-env", "vulkan1.0", "-o", spv_path, source_path]
    proc = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    if proc.returncode != 0:
        sys.stderr.write(proc.stdout)
        raise SystemExit(f"gen_spv: glslang failed on {source_path}")


def read_dwords(spv_path):
    with open(spv_path, "rb") as f:
        data = f.read()
    if len(data) % 4 != 0:
        raise SystemExit("gen_spv: SPIR-V size is not a multiple of 4")
    dwords = list(struct.unpack("<%dI" % (len(data) // 4), data))
    if not dwords or dwords[0] != 0x07230203:
        raise SystemExit("gen_spv: bad SPIR-V magic")
    return dwords


def emit_array(name, dwords):
    """8 dwords per line, trailing comma on every one, `};` glued to the last."""
    lines = [f"static const uint32_t {name}[] = {{\n"]
    for i in range(0, len(dwords), 8):
        chunk = "".join("0x%08x," % d for d in dwords[i:i + 8])
        lines.append(chunk + ("};\n" if i + 8 >= len(dwords) else "\n"))
    lines.append(f"static const uint32_t {name}_count = {len(dwords)};\n")
    return lines


def generate(glslang, verbose):
    lines = [HEADER]
    for source, name in TARGETS:
        with tempfile.TemporaryDirectory() as tmp:
            spv = os.path.join(tmp, source + ".spv")
            compile_shader(glslang, os.path.join(SHADERS, source), spv)
            dwords = read_dwords(spv)
        if verbose:
            print(f"  {source}: {len(dwords)} dwords ({len(dwords) * 4} bytes)")
        lines += emit_array(name, dwords)
    # The checked-in file uses CRLF; keep regenerated output byte-identical.
    return "".join(lines).replace("\n", "\r\n").encode("ascii")


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--glslang", default=default_glslang(),
                    help="path to the glslang CLI (default: tools/glslang/bin/glslang)")
    ap.add_argument("--check", action="store_true",
                    help="do not write; fail if vk_spv.inc differs")
    ap.add_argument("--verbose", action="store_true")
    args = ap.parse_args()

    if not os.path.exists(args.glslang) and not shutil.which(args.glslang):
        raise SystemExit(f"gen_spv: glslang not found at {args.glslang!r}\n"
                         "  fetch/download glslang, or pass --glslang PATH / set GLSLANG")

    generated = generate(args.glslang, args.verbose)

    if args.check:
        try:
            with open(OUT, "rb") as f:
                current = f.read()
        except FileNotFoundError:
            current = b""
        if current != generated:
            raise SystemExit("gen_spv: vk_spv.inc is stale - run 'make spv'")
        print("vk_spv.inc is up to date")
        return

    with open(OUT, "wb") as f:
        f.write(generated)
    print(f"wrote {os.path.relpath(OUT, REPO)} ({len(generated)} bytes)")


if __name__ == "__main__":
    main()
